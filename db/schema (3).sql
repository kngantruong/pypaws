-- CẢNH BÁO: phần "Xóa bảng cũ" ngay bên dưới XÓA SẠCH dữ liệu; dùng để reset trước buổi demo.

set client_encoding to 'UTF8';

/* ---------- Xóa bảng cũ (kể cả bảng nhận nuôi đã bỏ khỏi web) ---------- */
drop table if exists adoption_requests, adopters, adopt_pet_images, adopt_pets cascade;
drop table if exists notifications, candidates, image_embeddings, post_images, posts, users cascade;

/* ---------- users ---------- */
create table users (
    user_id     integer generated by default as identity primary key,
    email       varchar(255) not null,
    password    varchar(255) not null,                       -- chỉ lưu hash, không lưu mật khẩu thật
    full_name   varchar(100),
    phone       varchar(20),
    user_type   varchar(15)  not null default 'INDIVIDUAL'
                check (user_type in ('INDIVIDUAL','SHELTER','ADMIN')),
    created_at  timestamptz  not null default now()
);
create unique index ux_users_email on users (lower(email));  -- email không phân biệt hoa thường

/* ---------- posts: bài LOST / FOUND (khớp form PetReportPage) ----------
   Trạng thái bài (đã chốt với nhóm trưởng):
     ACTIVE    = bài đang hoạt động
     RESOLVED  = người LOST đã tìm thấy thú cưng
     CANCELLED = người đăng chủ động hủy bài
   Việc matching được quản lý riêng ở bảng candidates nên bài không có trạng thái MATCHED. */
create table posts (
    post_id           integer generated by default as identity primary key,
    report_code       varchar(30)  not null unique,   -- mã báo cáo, VD LOST-20261031-0001; trigger tự sinh
    user_id           integer      not null references users(user_id),
    post_type         varchar(10)  not null check (post_type in ('LOST','FOUND')),
    species           varchar(10)  not null check (species in ('DOG','CAT')),
    gender            varchar(10)  check (gender in ('MALE','FEMALE','UNKNOWN')),   -- tùy chọn
    breed             varchar(100),                                                  -- tùy chọn, tối đa 100 ký tự
    coat_color        varchar(50),                                                   -- tùy chọn, tối đa 50
    appearance_notes  varchar(300),                                                  -- tùy chọn, tối đa 300
    description       text         not null
                      check (char_length(btrim(description)) between 10 and 1000),  -- 10..1000 như frontend
    event_time        timestamptz  not null,                                         -- thời điểm bị lạc / tìm thấy
    location_text     varchar(255) not null check (btrim(location_text) <> ''),
    latitude          numeric(9,6),
    longitude         numeric(9,6),
    status            varchar(20)  not null default 'ACTIVE'
                      check (status in ('ACTIVE','RESOLVED','CANCELLED')),
    resolved_at       timestamptz,                    -- lúc bài chuyển sang RESOLVED
    resolution_source varchar(20)
                      check (resolution_source in ('PYPAWS_MATCH','SOCIAL_MEDIA','SHELTER','SELF_FOUND','OTHER')),
    data_source       varchar(10)  not null default 'USER'
                      check (data_source in ('USER','PETFACE')),
    created_at        timestamptz  not null default now(),
    -- tọa độ: hoặc để trống cả hai, hoặc có cả hai và đúng khoảng
    constraint ck_posts_latlng check (
        (latitude is null and longitude is null)
        or (latitude between -90 and 90 and longitude between -180 and 180)
    ),
    -- RESOLVED <=> có resolved_at; resolution_source chỉ có khi đã RESOLVED
    constraint ck_posts_resolved check ((status = 'RESOLVED') = (resolved_at is not null)),
    constraint ck_posts_resolution_source check (resolution_source is null or status = 'RESOLVED')
);
create index ix_posts_feed   on posts (post_type, species, status, created_at desc);
create index ix_posts_user   on posts (user_id);
create index ix_posts_recent on posts (created_at desc, post_id desc);

-- Tự sinh report_code ngay khi chèn bài: <LOẠI>-<YYYYMMDD giờ Việt Nam>-<post_id, tối thiểu 4 chữ số>.
-- Dùng post_id nên không bao giờ trùng. (Số cuối KHÔNG reset theo ngày.)
create or replace function trg_set_report_code() returns trigger
language plpgsql as $$
begin
    new.report_code := new.post_type || '-'
        || to_char(new.created_at at time zone 'Asia/Ho_Chi_Minh', 'YYYYMMDD') || '-'
        || lpad(new.post_id::text, greatest(4, length(new.post_id::text)), '0');
    return new;
end $$;
create trigger trg_posts_report_code before insert on posts
    for each row execute function trg_set_report_code();

/* ---------- post_images: tối đa 6 ảnh / bài, 1 ảnh bìa ---------- */
create table post_images (
    image_id    integer generated by default as identity primary key,
    post_id     integer      not null references posts(post_id) on delete cascade,
    image_path  varchar(500) not null,
    is_primary  boolean      not null default false,   -- = "Ảnh bìa" (cover) trên web
    sort_order  smallint     not null default 0,       -- thứ tự ảnh người dùng chọn (0,1,2...)
    created_at  timestamptz  not null default now()
);
create index ix_post_images_post on post_images (post_id);
-- mỗi bài chỉ có tối đa 1 ảnh bìa
create unique index ux_post_images_primary on post_images (post_id) where is_primary;

create or replace function trg_limit_post_images() returns trigger
language plpgsql as $$
begin
    if (select count(*) from post_images where post_id = new.post_id) >= 6 then
        raise exception 'Mỗi bài đăng tối đa 6 ảnh' using errcode = 'check_violation';
    end if;
    return new;
end $$;
create trigger trg_post_images_limit before insert on post_images
    for each row execute function trg_limit_post_images();

/* ---------- image_embeddings: vector DINOv2 do pipeline AI ghi ---------- */
create table image_embeddings (
    image_id       integer      not null references post_images(image_id) on delete cascade,
    model_name     varchar(50)  not null check (model_name in ('dinov2_pretrained','dinov2_finetuned')),
    model_version  varchar(50)  not null,
    embedding      bytea        not null,                         -- float32 bytes
    dim            smallint     not null check (dim > 0),
    dtype          varchar(10)  not null default 'float32' check (dtype = 'float32'),
    created_at     timestamptz  not null default now(),
    primary key (image_id, model_name, model_version)
);

/* ---------- candidates: kết quả gợi ý, LUÔN theo chiều LOST -> FOUND ----------
   query_post_id     = bài LOST
   candidate_post_id = bài FOUND (cùng loài)
   Dù bài mới đăng là LOST hay FOUND, cặp vẫn được lưu theo chiều này (trigger bên dưới bắt buộc),
   nên mỗi cặp chỉ có đúng 1 dòng.
   Trạng thái xác minh của người LOST:
     PENDING   = AI đề xuất, chưa được xử lý
     REJECTED  = người LOST chọn "không phải"
     CONTACTED = người LOST chọn liên hệ
     RESOLVED  = cặp bài được xác nhận đã giúp tìm lại thú cưng
     CANCELLED = matching không còn cần thiết */
create table candidates (
    candidate_id       integer generated by default as identity primary key,
    query_post_id      integer      not null references posts(post_id),
    candidate_post_id  integer      not null references posts(post_id),
    image_score        numeric(7,5),
    distance_km        numeric(9,2),
    time_gap_hours     numeric(10,2),
    final_score        numeric(7,5) not null,
    rank_no            integer      not null check (rank_no >= 1),   -- hạng trong danh sách của bài LOST
    passed_threshold   boolean      not null,
    reason             varchar(500),
    status             varchar(15)  not null default 'PENDING'
                       check (status in ('PENDING','REJECTED','CONTACTED','RESOLVED','CANCELLED')),
    decision_at        timestamptz,                 -- lúc người LOST thao tác
    resolved_at        timestamptz,                 -- lúc xác nhận hoàn tất
    resolution_source  varchar(20)
                       check (resolution_source in ('PYPAWS_MATCH','SOCIAL_MEDIA','SHELTER','SELF_FOUND','OTHER')),
    created_at         timestamptz  not null default now(),
    constraint ck_candidates_diff check (query_post_id <> candidate_post_id),
    constraint uq_candidates_pair unique (query_post_id, candidate_post_id),
    constraint ck_candidates_resolved check ((status = 'RESOLVED') = (resolved_at is not null)),
    constraint ck_candidates_decision check (
        (status = 'PENDING' and decision_at is null)
        or status = 'CANCELLED'
        or (status in ('REJECTED','CONTACTED','RESOLVED') and decision_at is not null)
    )
);
create index ix_candidates_query_rank on candidates (query_post_id, rank_no);
create index ix_candidates_found on candidates (candidate_post_id);

-- Bắt buộc đúng chiều: query = LOST, candidate = FOUND, cùng loài.
create or replace function trg_check_candidate_pair() returns trigger
language plpgsql as $$
declare
    v_lost_type text; v_lost_species text;
    v_found_type text; v_found_species text;
begin
    select p.post_type, p.species into v_lost_type, v_lost_species
      from posts p where p.post_id = new.query_post_id;
    select p.post_type, p.species into v_found_type, v_found_species
      from posts p where p.post_id = new.candidate_post_id;

    if v_lost_type is distinct from 'LOST' then
        raise exception 'query_post_id phải là bài LOST' using errcode = 'check_violation';
    end if;
    if v_found_type is distinct from 'FOUND' then
        raise exception 'candidate_post_id phải là bài FOUND' using errcode = 'check_violation';
    end if;
    if v_lost_species is distinct from v_found_species then
        raise exception 'Hai bài phải cùng loài' using errcode = 'check_violation';
    end if;
    return new;
end $$;
create trigger trg_candidates_pair before insert or update of query_post_id, candidate_post_id on candidates
    for each row execute function trg_check_candidate_pair();

/* ---------- notifications ---------- */
create table notifications (
    notification_id        integer generated by default as identity primary key,
    user_id                integer       not null references users(user_id),
    notification_type      varchar(30)   not null,
    title                  varchar(200)  not null,
    message                varchar(1000) not null,
    related_candidate_id   integer       references candidates(candidate_id) on delete set null,
    is_read                boolean       not null default false,
    created_at             timestamptz   not null default now()
);
create index ix_notifications_unread on notifications (user_id, is_read, created_at desc);
-- Chống gửi trùng: mỗi cặp matching chỉ có 1 thông báo "CANDIDATE_FOUND"
create unique index ux_notifications_candidate_event
    on notifications (related_candidate_id, notification_type)
    where related_candidate_id is not null and notification_type = 'CANDIDATE_FOUND';

/* ---------- Realtime cho demo: báo ngay khi có bài mới ----------
   pg_notify chỉ gửi khi transaction COMMIT, nên backend chèn bài + ảnh trong
   cùng một transaction (hàm create_post trong queries.sql làm sẵn việc này).
   Backend LISTEN kênh 'new_post' rồi đẩy xuống web (SSE/WebSocket).
   (Nếu dùng Supabase Realtime thì không cần trigger này.) */
create or replace function trg_notify_new_post() returns trigger
language plpgsql as $$
begin
    perform pg_notify('new_post',
        json_build_object('post_id', new.post_id, 'report_code', new.report_code,
                          'post_type', new.post_type, 'species', new.species)::text);
    return null;
end $$;
create trigger trg_posts_notify after insert on posts
    for each row execute function trg_notify_new_post();
